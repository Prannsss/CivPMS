import { expect, test } from "@playwright/test";
import { loginAs } from "./helpers/auth";
import { F4_OWNER, ensureF4Tenant } from "./f4-tenant";
const OUT = "/tmp/claude-0/-home-user/321de8e6-1b80-50a5-8310-7294642e121d/scratchpad/";
for (const scheme of ["light", "dark"] as const) {
  test(`states ${scheme}`, async ({ browser }) => {
    const t = await ensureF4Tenant();
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: scheme });
    await loginAs(context, F4_OWNER);
    const page = await context.newPage();
    await page.goto(`/projects/${t.showcaseId}/wbs`);
    await page.evaluate(() => localStorage.setItem("civpms.wbs.view", "list"));
    await page.reload();
    const row = (c: string) => page.locator(`[data-testid=wbs-row][data-wbs-code="${c}"]`);
    await row("1.1").getByRole("button", { name: /^Actions for/ }).click();
    await page.screenshot({ path: OUT + `s-menu-${scheme}.png` });
    await page.getByRole("menuitem", { name: /Add sub-deliverable|Add work package/ }).first().click();
    await page.waitForTimeout(400);
    await page.screenshot({ path: OUT + `s-dialog-${scheme}.png` });
    await page.keyboard.press("Escape");
    await row("2").getByRole("button", { name: /^Actions for/ }).click();
    await page.getByRole("menuitem", { name: /Delete deliverable/ }).click();
    await page.waitForTimeout(400);
    await page.screenshot({ path: OUT + `s-delete-${scheme}.png` });
    await page.getByRole("alertdialog").getByRole("button", { name: "Cancel" }).click();
    await row("1.2").getByRole("button", { name: /^Duration of/ }).click();
    await page.keyboard.type("abc");
    await page.keyboard.press("Enter");
    await page.waitForTimeout(300);
    await page.screenshot({ path: OUT + `s-inline-${scheme}.png` });
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: /Recently deleted/ }).click();
    await page.waitForTimeout(400);
    await page.screenshot({ path: OUT + `s-trash-${scheme}.png` });
    await page.keyboard.press("Escape");
    await page.goto(`/projects/${t.showcaseId}/calendar`);
    await page.locator('[data-testid=calendar-month] button[data-date="2026-10-21"]').click({ button: "right" });
    await page.waitForTimeout(300);
    await page.screenshot({ path: OUT + `s-day-${scheme}.png` });
    await page.getByTestId("calendar-day-panel").getByRole("button", { name: "Mark as non-working day" }).click();
    await page.getByRole("button", { name: "Save changes" }).click();
    await expect(page.getByRole("alertdialog")).toBeVisible();
    await page.waitForTimeout(400);
    await page.screenshot({ path: OUT + `s-moves-${scheme}.png` });
    await page.getByRole("alertdialog").getByRole("button", { name: "Cancel" }).click();
    await page.getByRole("button", { name: "Discard" }).click();
    await context.close();
  });
}
